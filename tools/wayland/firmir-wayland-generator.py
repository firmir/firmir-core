#!/usr/bin/env python3
"""Generate lightweight C++ Wayland protocol wrappers using only libwayland."""
import argparse
import xml.etree.ElementTree as ET
from pathlib import Path


def camel(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def class_name(native):
    return camel(native[3:] if native.startswith("wl_") else native)


def method(name):
    value = camel(name)
    return value[:1].lower() + value[1:]


def cpp_type(arg, request=False):
    kind = arg.get("type")
    if kind == "int": return "std::int32_t"
    if kind == "uint": return "std::uint32_t"
    if kind == "fixed": return "wl_fixed_t"
    if kind == "string": return "const char*"
    if kind == "array": return "wl_array*"
    if kind == "fd": return "int"
    if kind in ("object", "new_id"):
        return (arg.get("interface") or "wl_proxy") + "*"
    return "std::uint32_t"


def generate_client(root):
    deferred = []
    out = ["// Generated by firmir-wayland-generator. Do not edit.\n#pragma once\n",
           "#include <firmir/wayland/client/proxy.hpp>\n",
           "#include <firmir/wayland/client/registry.hpp>\n",
           "#include <functional>\n#include <cstdint>\n#include <utility>\n\n",
           "namespace Firmir { namespace Wayland { namespace Client {\n\n"]
    for interface in root.findall("interface"):
        if interface.get("name") not in ("wl_display", "wl_registry"):
            out.append(f"class {class_name(interface.get('name'))};\n")
    out.append("\n")
    for interface in root.findall("interface"):
        if interface.get("name") in ("wl_display", "wl_registry"):
            continue
        native = interface.get("name")
        cls = class_name(native)
        requests = list(interface.findall("request"))
        destructor = next((method(r.get("name")) for r in requests
                           if r.get("type") == "destructor"), None)
        out.append(f"class {cls} : public Proxy<{native}> {{\npublic:\n")
        out.append(f"    using Native = {native};\n")
        if destructor:
            out.append(f"    explicit {cls}({native}* value = nullptr) : Proxy<{native}>(value, &{native}_{destructor}) {{}}\n")
        else:
            out.append(f"    explicit {cls}({native}* value = nullptr) : Proxy<{native}>(value, []({native}* p) {{ wl_proxy_destroy(reinterpret_cast<wl_proxy*>(p)); }}) {{}}\n")
        out.append(f"    static {cls} bind(Registry& registry, std::uint32_t name, std::uint32_t version) {{\n")
        out.append(f"        return {cls}(static_cast<{native}*>(wl_registry_bind(registry.handle(), name, &{native}_interface, version)));\n    }}\n")
        for req in requests:
            if req.get("type") == "destructor":
                continue
            args = list(req.findall("arg"))
            new_ids = [a for a in args if a.get("type") == "new_id"]
            if new_ids and not new_ids[0].get("interface"):
                continue
            result = class_name(new_ids[0].get("interface")) if new_ids else "void"
            ordinary = [a for a in args if a.get("type") != "new_id"]
            params = ", ".join(f"{cpp_type(a, True)} {a.get('name')}" for a in ordinary)
            if new_ids:
                out.append(f"    {result} {method(req.get('name'))}({params});\n")
                call_args = ["m_handle"] + [a.get("name") for a in ordinary]
                call = f"{native}_{req.get('name')}({', '.join(call_args)})"
                deferred.append(f"inline {result} {cls}::{method(req.get('name'))}({params}) {{\n")
                deferred.append(f"    return {result}({call});\n}}\n")
                continue
            out.append(f"    {result} {method(req.get('name'))}({params}) {{\n")
            call_args = ["m_handle"] + [a.get("name") for a in ordinary]
            call = f"{native}_{req.get('name')}({', '.join(call_args)})"
            out.append(f"        {call};\n")
            out.append("    }\n")
        events = list(interface.findall("event"))
        if events:
            out.append("    struct Listener {\n")
            for event in events:
                args = list(event.findall("arg"))
                types = ", ".join(cpp_type(a) for a in args)
                out.append(f"        std::function<void({types})> {method(event.get('name'))};\n")
            out.append("    };\n    void setListener(Listener listener) {\n        m_listener = std::move(listener);\n")
            out.append(f"        {native}_add_listener(m_handle, &s_listener, this);\n    }}\n")
            for event in events:
                args = list(event.findall("arg"))
                native_args = ", ".join(f"{cpp_type(a)} {a.get('name')}" for a in args)
                prefix = f"void* data, {native}*" + (", " if native_args else "")
                out.append(f"    static void on_{event.get('name')}({prefix}{native_args}) {{\n")
                out.append(f"        auto* self = static_cast<{cls}*>(data);\n")
                values = ", ".join(a.get("name") for a in args)
                out.append(f"        if (self->m_listener.{method(event.get('name'))}) self->m_listener.{method(event.get('name'))}({values});\n    }}\n")
            entries = ", ".join(f"&on_{e.get('name')}" for e in events)
            out.append(f"    inline static const {native}_listener s_listener = {{{entries}}};\n")
            out.append("    Listener m_listener;\n")
        out.append("};\n\n")
    out.extend(deferred)
    out.append("}}} // namespace Firmir::Wayland::Client\n")
    return "".join(out)


def generate_server(root):
    out = ["// Generated by firmir-wayland-generator. Do not edit.\n#pragma once\n",
           "#include <cstdint>\n#include <wayland-server-core.h>\n\n",
           "namespace Firmir { namespace Wayland { namespace Server {\n\n"]
    for interface in root.findall("interface"):
        native = interface.get("name")
        if native in ("wl_display", "wl_registry"):
            continue
        cls = class_name(native)
        out.append(f"class {cls} {{\npublic:\n")
        out.append(f"    explicit {cls}(wl_resource* resource = nullptr) : m_resource(resource) {{}}\n")
        out.append("    wl_resource* resource() const { return m_resource; }\n")
        out.append(f"    static const wl_interface* interface() {{ return &{native}_interface; }}\n")
        for event in interface.findall("event"):
            args = list(event.findall("arg"))
            params = ", ".join(f"{cpp_type(a)} {a.get('name')}" for a in args)
            values = ", ".join(["m_resource"] + [a.get("name") for a in args])
            out.append(f"    void {method(event.get('name'))}({params}) {{\n")
            out.append(f"        if (m_resource) {native}_send_{event.get('name')}({values});\n    }}\n")
        out.append("};\n\n")
    out.append("}}} // namespace Firmir::Wayland::Server\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("xml", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--mode", choices=("client", "server"), required=True)
    parser.add_argument("--protocol-header", required=True)
    args = parser.parse_args()
    root = ET.parse(args.xml).getroot()
    body = generate_client(root) if args.mode == "client" else generate_server(root)
    body = body.replace("#pragma once\n", f"#pragma once\n#include <{args.protocol_header}>\n", 1)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(body)


if __name__ == "__main__":
    main()
